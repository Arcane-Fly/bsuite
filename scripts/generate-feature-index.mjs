#!/usr/bin/env node
/**
 * Render docs/00-roadmap/BSUITE-FEATURE-INDEX.md FROM bsuite-feature-index.json.
 *
 * WHY THIS EXISTS. The parent index was hand-maintained beside a 666-row JSON,
 * and a hand-kept mirror of a machine-sized register drifts by construction.
 * Measured 2026-08-31: the JSON carried 666 features across 29 modules while the
 * markdown's own header still read "659 features across 13 modules" and it
 * mentioned only 572 feature ids — a 94-row hole. The operator's read was that
 * the index had "gone". It had not; it had stopped being true, which from the
 * outside is the same thing.
 *
 * ONE ROW, ONE TRUTH: the JSON is the register, this markdown is a VIEW of it.
 * Everything above the marker is prose a person owns; everything below is
 * generated and must never be hand-edited.
 *
 *   node scripts/generate-feature-index.mjs           # write
 *   node scripts/generate-feature-index.mjs --check   # CI: fail if the committed
 *                                                     # file is not what the JSON renders
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const JSON_PATH = path.join(ROOT, 'docs/00-roadmap/bsuite-feature-index.json');
const MD_PATH = path.join(ROOT, 'docs/00-roadmap/BSUITE-FEATURE-INDEX.md');
const MARKER = '<!-- GENERATED FROM bsuite-feature-index.json — DO NOT HAND-EDIT BELOW THIS LINE -->';

export function loadRows(jsonText) {
  const d = JSON.parse(jsonText);
  return Array.isArray(d) ? d : d.features || d.rows || [];
}

/** `a · b +N` — the estate's existing rendering for a truncated path list. */
export function pathList(paths, { code = true } = {}) {
  const list = (paths || []).filter(Boolean);
  if (list.length === 0) return '**none**';
  const shown = list.slice(0, 2).map((p) => (code ? `\`${p}\`` : p)).join(' · ');
  return list.length > 2 ? `${shown} +${list.length - 2}` : shown;
}

export function renderRow(f) {
  const noUi = f.ui_touched === false ? ' ·no-ui' : '';
  const status = f.build_status === 'live' ? 'live' : `**${f.build_status || 'unknown'}**`;
  const docs = pathList((f.docs || []).map((d) => (typeof d === 'string' ? d : d.path)));
  const code = pathList(f.code_anchors);
  const siblings = f.sibling_class ? `${f.sibling_class} (${f.sibling_count ?? '?'})` : '—';
  const entry = f.entry_point || '—';
  return `| **${f.name}**<br>\`${f.id}\`${noUi} | ${f.module} | ${status} | ${entry} | ${code} | ${docs} | ${siblings} |`;
}

/**
 * Sections keep the order they already had, so regenerating an unchanged index
 * produces an empty diff. A capability area the JSON has and the markdown does
 * not is APPENDED — it is new, and burying it mid-file would hide it.
 */
export function sectionOrder(existingMd, areas) {
  const seen = [];
  for (const line of existingMd.split('\n')) {
    if (line.startsWith('## ')) {
      const a = line.slice(3).trim();
      if (areas.has(a) && !seen.includes(a)) seen.push(a);
    }
  }
  for (const a of [...areas].sort()) if (!seen.includes(a)) seen.push(a);
  return seen;
}

export function render(rows, existingMd) {
  const byArea = new Map();
  for (const f of rows) {
    const a = f.capability_area || '(unclassified)';
    if (!byArea.has(a)) byArea.set(a, []);
    byArea.get(a).push(f);
  }
  const order = sectionOrder(existingMd, new Set(byArea.keys()));
  const modules = new Set(rows.map((r) => r.module));
  const out = [];
  out.push(MARKER, '');
  out.push(`**${rows.length} features across ${modules.size} modules · ${byArea.size} capability areas**`, '');
  out.push('Generated by `scripts/generate-feature-index.mjs` from `bsuite-feature-index.json`. Edit the JSON, not this file.', '');
  for (const area of order) {
    const list = byArea.get(area) || [];
    // (module, id) — the order the index already used.
    list.sort((a, b) => (a.module === b.module ? String(a.id).localeCompare(String(b.id)) : String(a.module).localeCompare(String(b.module))));
    const live = list.filter((f) => f.build_status === 'live').length;
    const undoc = list.filter((f) => f.doc_coverage === 'undocumented').length;
    out.push(`## ${area}`, '');
    out.push(`${list.length} features · ${live} live · ${undoc} undocumented`, '');
    out.push('| Feature | Module | Status | Entry point | Code | Docs | Siblings |');
    out.push('|---|---|---|---|---|---|---|');
    for (const f of list) out.push(renderRow(f));
    out.push('');
  }
  return out.join('\n').replace(/\n+$/, '\n');
}

function preambleOf(md) {
  const i = md.indexOf(MARKER);
  if (i !== -1) return md.slice(0, i);
  const j = md.search(/\n## (?!How to read a row|Provenance of every row)/);
  return j === -1 ? md : md.slice(0, j + 1);
}

function main() {
  const check = process.argv.includes('--check');
  const rows = loadRows(fs.readFileSync(JSON_PATH, 'utf8'));
  const existing = fs.existsSync(MD_PATH) ? fs.readFileSync(MD_PATH, 'utf8') : '';
  const next = `${preambleOf(existing).replace(/\s+$/, '')}\n\n${render(rows, existing)}`;
  if (check) {
    if (existing === next) {
      console.log(`feature-index: in sync (${rows.length} rows)`);
      process.exit(0);
    }
    console.error('feature-index: BSUITE-FEATURE-INDEX.md is not what bsuite-feature-index.json renders.');
    console.error('  The JSON is the register; the markdown is a view of it.');
    console.error('  Run: node scripts/generate-feature-index.mjs');
    process.exit(1);
  }
  fs.writeFileSync(MD_PATH, next);
  console.log(`feature-index: wrote ${rows.length} rows across ${new Set(rows.map((r) => r.module)).size} modules`);
}

if (process.argv.includes('--self-test')) {
  const cases = [];
  const t = (n, a, e) => cases.push({ n, ok: JSON.stringify(a) === JSON.stringify(e), a, e });
  t('pathList: empty renders none', pathList([]), '**none**');
  t('pathList: one is not truncated', pathList(['a.ts']), '`a.ts`');
  t('pathList: two are both shown', pathList(['a.ts', 'b.ts']), '`a.ts` · `b.ts`');
  t('pathList: three shows two and a count', pathList(['a', 'b', 'c']), '`a` · `b` +1');
  t('pathList: nulls are dropped, not rendered', pathList(['a', null, undefined]), '`a`');
  const f = { id: 'x.y', name: 'N', module: 'crm7', build_status: 'live', ui_touched: true, code_anchors: ['a'], docs: [], sibling_class: 'c', sibling_count: 3, entry_point: 'E' };
  t('row: a live ui feature renders plainly', renderRow(f), '| **N**<br>`x.y` | crm7 | live | E | `a` | **none** | c (3) |');
  t('row: a non-live status is bolded so it cannot be skimmed past',
    renderRow({ ...f, build_status: 'unwired' }).includes('| **unwired** |'), true);
  t('row: ui_touched false is marked no-ui, because it decides whether D8 applies',
    renderRow({ ...f, ui_touched: false }).includes('`x.y` ·no-ui'), true);
  t('row: docs given as objects are read by .path',
    renderRow({ ...f, docs: [{ path: 'd.md' }] }).includes('`d.md`'), true);
  t('order: existing sections keep their order', sectionOrder('## B\n## A\n', new Set(['A', 'B'])), ['B', 'A']);
  t('order: a NEW area is appended, never buried mid-file',
    sectionOrder('## B\n', new Set(['B', 'Zed', 'Anew'])), ['B', 'Anew', 'Zed']);
  t('order: a section the JSON no longer has is dropped', sectionOrder('## Gone\n## B\n', new Set(['B'])), ['B']);
  const bad = cases.filter((c) => !c.ok);
  for (const c of bad) console.error(`FAIL ${c.n}: expected ${JSON.stringify(c.e)}, got ${JSON.stringify(c.a)}`);
  console.log(bad.length ? `generate-feature-index --self-test: ${bad.length} FAILED` : `generate-feature-index --self-test: OK (${cases.length} cases)`);
  process.exit(bad.length ? 1 : 0);
}
main();
