#!/usr/bin/env node
/**
 * generate-docs-directory-index — write a README.md index into every docs
 * directory that holds documents and has none.
 *
 * WHY. The estate's own standard is "Every `docs/` folder has a README.md index"
 * (docs/20260504-bsuite-documentation-hub-v1.00W.md). It was enforced for ADR
 * directories only — check-doc-naming refuses an ADR folder with no index, on the
 * reasoning that "an ADR nobody can find is an ADR nobody reads". That reasoning
 * is not specific to ADRs. On 2026-08-27, 11 directories holding 70 documents had
 * no index at all, the largest being docs/00-roadmap with 28.
 *
 * GENERATED, NOT HAND-WRITTEN, deliberately. A hand-maintained index is a second
 * copy of the directory listing, and it goes stale the first time someone adds a
 * file without remembering it — which is exactly how the parent and crm7 copies of
 * drift-scan.mjs came to disagree. Re-run this and the index is correct again.
 *
 * Each row carries what a person actually needs to choose a document: its title
 * (the H1, not the filename), its status letter, and its date. Nothing is
 * summarised or interpreted — a generator that paraphrases is a generator that
 * lies as soon as the document changes.
 *
 *   node scripts/generate-docs-directory-index.mjs [--check] [root ...]
 *
 * --check writes nothing and exits non-zero if any index is missing or stale, so
 * this can gate as well as generate.
 */
import fs from 'node:fs'
import path from 'node:path'

const args = process.argv.slice(2)
const checkOnly = args.includes('--check')
const roots = args.filter((a) => !a.startsWith('--'))
const SKIP_DIR = new Set(['archive', 'node_modules', 'dist', '.git', 'references', 'reference', 'recovered', 'nav'])
const INDEX_NAMES = new Set(['readme.md', 'index.md', 'status.md'])
const STATUS = { W: 'Working', D: 'Draft', R: 'Review', A: 'Approved', F: 'Frozen' }

/** The H1, which is what the author called it — the filename is a slug of it at best. */
function titleOf(file) {
  try {
    for (const line of fs.readFileSync(file, 'utf8').split('\n').slice(0, 40)) {
      const m = line.match(/^#\s+(.+?)\s*$/)
      if (m) return m[1].replace(/\s*[—-]\s*$/, '')
    }
  } catch { /* unreadable — fall through to the filename */ }
  return path.basename(file, '.md')
}

function meta(name) {
  const m = name.match(/^(\d{8})-.*-v(\d+\.\d+)([WDRAF])\.md$/)
  if (!m) return { date: '', status: '' }
  return { date: `${m[1].slice(0, 4)}-${m[1].slice(4, 6)}-${m[1].slice(6)}`, status: STATUS[m[3]] || m[3] }
}

function render(dir, files) {
  const rows = files
    .map((f) => ({ f, ...meta(f), title: titleOf(path.join(dir, f)) }))
    .sort((a, b) => (b.date || '').localeCompare(a.date || '') || a.f.localeCompare(b.f))
  const out = [
    `# ${dir.split('/').filter(Boolean).slice(-1)[0]}`,
    '',
    `${rows.length} document${rows.length === 1 ? '' : 's'}, newest first.`,
    '',
    '<!-- GENERATED by scripts/generate-docs-directory-index.mjs — re-run it rather than editing rows. -->',
    '',
    '| Document | Status | Dated |',
    '|---|---|---|',
    ...rows.map((r) => `| [${r.title.replace(/\|/g, '\\|')}](${r.f}) | ${r.status || '—'} | ${r.date || '—'} |`),
    '',
  ]
  return out.join('\n')
}

function walk(dir, found) {
  let entries
  try { entries = fs.readdirSync(dir, { withFileTypes: true }) } catch { return }
  const files = []
  for (const e of entries) {
    if (e.isDirectory()) {
      if (!SKIP_DIR.has(e.name.toLowerCase())) walk(path.join(dir, e.name), found)
    } else if (e.isFile() && e.name.endsWith('.md')) files.push(e.name)
  }
  if (!files.length) return
  const hasIndex = files.some((f) => INDEX_NAMES.has(f.toLowerCase()))
  found.push({ dir, files: files.filter((f) => !INDEX_NAMES.has(f.toLowerCase())), hasIndex })
}

const targets = []
for (const r of (roots.length ? roots : ['docs'])) walk(r, targets)

let wrote = 0
const stale = []
for (const t of targets) {
  if (t.hasIndex || !t.files.length) continue
  const p = path.join(t.dir, 'README.md')
  const body = render(t.dir, t.files)
  if (checkOnly) { stale.push(p); continue }
  fs.writeFileSync(p, body)
  wrote += 1
  console.log(`  wrote ${p} (${t.files.length} doc(s))`)
}

if (checkOnly) {
  if (stale.length) {
    console.error(`generate-docs-directory-index: ${stale.length} directory(ies) hold documents and no index:`)
    for (const s of stale) console.error(`  ${s}`)
    console.error('  Run: node scripts/generate-docs-directory-index.mjs <root>')
    process.exit(1)
  }
  console.log(`generate-docs-directory-index: every one of ${targets.length} doc directory(ies) has an index`)
  process.exit(0)
}
console.log(`generate-docs-directory-index: wrote ${wrote} index(es) across ${targets.length} directory(ies)`)
