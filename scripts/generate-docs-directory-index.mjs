#!/usr/bin/env node
/**
 * generate-docs-directory-index — write a README.md index into every docs
 * directory that holds documents and has none.
 *
 * WHY. The estate's own standard is "Every `docs/` folder has a README.md index"
 * (docs/20260504-bsuite-documentation-hub-v1.00W.md). It was enforced for ADR
 * directories only — check-doc-naming refuses an ADR folder with no index, on the
 * reasoning that "an ADR nobody can find is an ADR nobody reads". That reasoning
 * is not specific to ADRs. On 2026-08-27, 11 directories holding 70 documents had
 * no index at all, the largest being docs/00-roadmap with 28.
 *
 * GENERATED, NOT HAND-WRITTEN, deliberately. A hand-maintained index is a second
 * copy of the directory listing, and it goes stale the first time someone adds a
 * file without remembering it — which is exactly how the parent and crm7 copies of
 * drift-scan.mjs came to disagree. Re-run this and the index is correct again.
 *
 * Each row carries what a person actually needs to choose a document: its title
 * (the H1, not the filename), its status letter, and its date. Nothing is
 * summarised or interpreted — a generator that paraphrases is a generator that
 * lies as soon as the document changes.
 *
 *   node scripts/generate-docs-directory-index.mjs [--check] [root ...]
 *
 * --check writes nothing and exits non-zero if any index is missing or stale, so
 * this can gate as well as generate.
 */
import fs from 'node:fs'
import path from 'node:path'

const args = process.argv.slice(2)
const checkOnly = args.includes('--check')
const roots = args.filter((a) => !a.startsWith('--'))
const SKIP_DIR = new Set(['archive', 'node_modules', 'dist', '.git', 'references', 'reference', 'recovered', 'nav'])
const INDEX_NAMES = new Set(['readme.md', 'index.md', 'status.md'])
const STATUS = { W: 'Working', D: 'Draft', R: 'Review', A: 'Approved', F: 'Frozen' }

/** The H1, which is what the author called it — the filename is a slug of it at best. */
function titleOf(file) {
  try {
    for (const line of fs.readFileSync(file, 'utf8').split('\n').slice(0, 40)) {
      const m = line.match(/^#\s+(.+?)\s*$/)
      if (m) return m[1].replace(/\s*[—-]\s*$/, '')
    }
  } catch { /* unreadable — fall through to the filename */ }
  return path.basename(file, '.md')
}

function meta(name) {
  const m = name.match(/^(\d{8})-.*-v(\d+\.\d+)([WDRAF])\.md$/)
  if (!m) return { date: '', status: '' }
  return { date: `${m[1].slice(0, 4)}-${m[1].slice(4, 6)}-${m[1].slice(6)}`, status: STATUS[m[3]] || m[3] }
}

/**
 * THE MARKER IS THE PROPERTY LINE.
 *
 * Everything ABOVE it belongs to whoever wrote the file; everything from it down
 * belongs to this script. A README with NO marker is not an index this tool
 * owns — it is somebody's document that happens to sit in a docs directory, and
 * the generator must not touch it at all.
 *
 * That distinction is not decoration. Measured 2026-09-04: `docs/plans/README.md`
 * has no marker, carries a hand-written banner about the R80.3 -> R80.4
 * restructure that the plan-currency gate special-cases by name, and a
 * whole-file regeneration replaced all of it with a bare table — -672/+270
 * across 11 files, and most of it was meaning.
 */
export const GENERATED_MARKER =
  '<!-- GENERATED by scripts/generate-docs-directory-index.mjs — re-run it rather than editing rows. -->'

/** The generator's own count line, which it reclaims rather than preserves. */
const COUNT_RE = /^\d+ documents?, newest first\.$/

/**
 * Split a file into the part this script must preserve and the part it owns.
 * Returns null when the file carries no marker — the "not ours" answer.
 */
export function splitAtMarker(text) {
  const lines = text.split('\n')
  const i = lines.findIndex((l) => l.trim() === GENERATED_MARKER)
  if (i === -1) return null
  // Everything above the marker is preserved verbatim, except the generator's
  // own count line: it wrote that, it may reclaim it, and leaving it there is
  // how the count goes stale while the table below is correct.
  const above = lines.slice(0, i).filter((l) => !COUNT_RE.test(l.trim()))
  while (above.length && above[above.length - 1].trim() === '') above.pop()
  return { above, region: lines.slice(i).join('\n') }
}

function render(dir, files) {
  const rows = files
    .map((f) => ({ f, ...meta(f), title: titleOf(path.join(dir, f)) }))
    .sort((a, b) => (b.date || '').localeCompare(a.date || '') || a.f.localeCompare(b.f))
  return [
    GENERATED_MARKER,
    '',
    `${rows.length} document${rows.length === 1 ? '' : 's'}, newest first.`,
    '',
    '| Document | Status | Dated |',
    '|---|---|---|',
    ...rows.map((r) => `| [${r.title.replace(/\|/g, '\\|')}](${r.f}) | ${r.status || '—'} | ${r.date || '—'} |`),
    '',
  ].join('\n')
}

/** A brand-new index: a heading, then the generated region. */
function renderNewFile(dir, files) {
  return [`# ${dir.split('/').filter(Boolean).slice(-1)[0]}`, '', render(dir, files)].join('\n')
}

function walk(dir, found) {
  let entries
  try { entries = fs.readdirSync(dir, { withFileTypes: true }) } catch { return }
  const files = []
  for (const e of entries) {
    if (e.isDirectory()) {
      if (!SKIP_DIR.has(e.name.toLowerCase())) walk(path.join(dir, e.name), found)
    } else if (e.isFile() && e.name.endsWith('.md')) files.push(e.name)
  }
  if (!files.length) return
  const hasIndex = files.some((f) => INDEX_NAMES.has(f.toLowerCase()))
  found.push({ dir, files: files.filter((f) => !INDEX_NAMES.has(f.toLowerCase())), hasIndex })
}

if (args.includes('--self-test')) {
  let bad = 0
  const fail = (m) => { console.error(`  FAIL ${m}`); bad += 1 }

  // A README with NO marker is not ours. This is the case that made a
  // whole-file regeneration destroy docs/plans/README.md's R80.3 banner.
  if (splitAtMarker('# Plans\n\n> A hand-written banner.\n') !== null)
    fail('a README with no marker was treated as a generated index')

  // A banner ABOVE the marker survives byte-for-byte.
  const banner = '# Plans\n\n> **Predates the R80.3 → R80.4 restructure (2026-08-06).**\n> Paths below are HISTORICAL.\n'
  const withMarker = `${banner}\n${GENERATED_MARKER}\n\n3 documents, newest first.\n\n| Document | Status | Dated |\n|---|---|---|\n`
  const split = splitAtMarker(withMarker)
  if (!split) fail('a marked file was not recognised')
  else if (split.above.join('\n') + '\n' !== banner)
    fail(`the banner above the marker was not preserved byte-for-byte: ${JSON.stringify(split.above.join('\n'))}`)

  // The generator's OWN count line is reclaimed, not preserved — otherwise the
  // count above the marker goes stale while the table below is correct.
  const withCountAbove = `# X\n\n5 documents, newest first.\n\n${GENERATED_MARKER}\n\n2 documents, newest first.\n`
  const s2 = splitAtMarker(withCountAbove)
  if (s2 && s2.above.some((l) => /documents, newest first/.test(l)))
    fail('the generator\'s own count line above the marker was preserved and will go stale')

  // A stale ROW must be visible as a difference. Same directory, different
  // table — the check compares regions, so this cannot come back equal.
  const a = `${GENERATED_MARKER}\n\n1 document, newest first.\n\n| Document | Status | Dated |\n|---|---|---|\n| [A](a.md) | Working | 2026-01-01 |\n`
  const b = `${GENERATED_MARKER}\n\n1 document, newest first.\n\n| Document | Status | Dated |\n|---|---|---|\n| [B](b.md) | Working | 2026-01-01 |\n`
  if (a === b) fail('two different tables compared equal — the check cannot see a stale row')

  console.log(
    bad === 0
      ? 'generate-docs-directory-index --self-test: 5 assertions — an unmarked README is not ours, ' +
          'a banner above the marker survives byte-for-byte, the generator reclaims its own count line, ' +
          'and a changed row is visible as a difference.'
      : `generate-docs-directory-index --self-test: ${bad} FAILED`,
  )
  process.exit(bad === 0 ? 0 : 1)
}

const targets = []
for (const r of (roots.length ? roots : ['docs'])) walk(r, targets)

let wrote = 0
const stale = []
const notOurs = []
for (const t of targets) {
  if (!t.files.length) continue
  const p = path.join(t.dir, 'README.md')

  let current = null
  try { current = fs.readFileSync(p, 'utf8') } catch { /* absent — we create it */ }

  // A README with no marker is somebody's document, not our index. Leave it
  // entirely alone and say so once, rather than silently rewriting it or
  // silently ignoring it.
  if (current !== null) {
    const split = splitAtMarker(current)
    if (!split) { notOurs.push(p); continue }
    const body = [...split.above, '', render(t.dir, t.files)].join('\n')
    if (body === current) continue
    if (checkOnly) { stale.push(p); continue }
    fs.writeFileSync(p, body)
  } else {
    if (checkOnly) { stale.push(p); continue }
    fs.writeFileSync(p, renderNewFile(t.dir, t.files))
  }
  wrote += 1
  console.log(`  wrote ${p} (${t.files.length} doc(s))`)
}

if (notOurs.length) {
  // Said out loud, always. A README with no marker is deliberately untouched,
  // and a reader comparing "27 directories" against "17 indexes" deserves to
  // know which ones this tool does not own rather than assuming it missed them.
  console.log(
    `generate-docs-directory-index: ${notOurs.length} README(s) carry no GENERATED marker and were left alone:`,
  )
  for (const n of notOurs) console.log(`  ${n}`)
}

if (checkOnly) {
  if (stale.length) {
    console.error(`generate-docs-directory-index: ${stale.length} index(es) MISSING or OUT OF DATE:`)
    for (const s of stale) console.error(`  ${s}`)
    console.error('  Run: node scripts/generate-docs-directory-index.mjs <root>')
    process.exit(1)
  }
  console.log(`generate-docs-directory-index: every one of ${targets.length} doc directory(ies) has an index`)
  process.exit(0)
}
console.log(`generate-docs-directory-index: wrote ${wrote} index(es) across ${targets.length} directory(ies)`)
